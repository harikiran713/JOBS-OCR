"""Request authentication for the local API.

The backend binds to 127.0.0.1 only, and additionally requires a per-launch
random token generated by the Electron main process. Other local processes or
web pages cannot call the API without it. The token is accepted from the
``Authorization: Bearer`` header, or the ``token`` query parameter for <img>
requests (page renders) which cannot carry headers.
"""

from __future__ import annotations

import hmac
import os

from fastapi import HTTPException, Request, status

_TOKEN: str | None = None


def configure_token(token: str | None) -> None:
    global _TOKEN
    _TOKEN = token


def get_token() -> str | None:
    return _TOKEN if _TOKEN is not None else os.environ.get("MMI_API_TOKEN")


def require_token(request: Request) -> None:
    expected = get_token()
    if not expected:
        if os.environ.get("MMI_DEV_NO_AUTH") == "1":
            return
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, "API token not configured")
    supplied = ""
    auth = request.headers.get("authorization", "")
    if auth.lower().startswith("bearer "):
        supplied = auth[7:].strip()
    elif request.method == "GET" and "token" in request.query_params:
        supplied = request.query_params["token"]
    if not supplied or not hmac.compare_digest(supplied, expected):
        raise HTTPException(status.HTTP_401_UNAUTHORIZED, "Invalid or missing API token")
